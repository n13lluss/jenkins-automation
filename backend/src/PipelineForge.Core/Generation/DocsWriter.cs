using System.Text;
using PipelineForge.Core.Compliance;
using PipelineForge.Core.Model;

namespace PipelineForge.Core.Generation;

public sealed record RequiredCredential(string Id, string Kind, string Purpose);

public static class DocsWriter
{
    public static IReadOnlyList<string> RequiredPlugins(GenerationContext ctx)
    {
        var c = ctx.Config;
        var plugins = new List<string>
        {
            "workflow-aggregator (Pipeline)",
            "pipeline-model-definition (Declarative Pipeline)",
            "bitbucket-branch-source or github-branch-source (Multibranch)",
            "pipeline-utility-steps (readYaml)",
            "credentials-binding",
            "timestamper",
            "junit",
            "warnings-ng (SARIF reports)",
        };
        plugins.Add(ctx.IsKubernetes ? "kubernetes (pod agents)" : "docker-workflow (Docker agents)");
        if (!ctx.IsKubernetes) plugins.Add("ws-cleanup");
        if (c.Quality.Enabled) plugins.Add("sonar (SonarQube Scanner for Jenkins)");
        if (ctx.DeployEnvironments.Any(e => e.Deploy.Type == DeployTargetType.DockerSsh)) plugins.Add("ssh-agent");
        if (ctx.DeployEnvironments.Any(e => e.Deploy.Type == DeployTargetType.AzureAppService)) plugins.Add("azure-credentials");
        return plugins;
    }

    public static IReadOnlyList<RequiredCredential> RequiredCredentials(GenerationContext ctx)
    {
        var c = ctx.Config;
        var list = new List<RequiredCredential>();
        void Add(string id, string kind, string purpose)
        {
            if (list.All(x => x.Id != id)) list.Add(new(id, kind, purpose));
        }
        if (c.Registry is { } reg && ctx.ImageModules.Count > 0) Add(reg.CredentialId, "Username with password", $"Push images to {reg.Host}");
        if (c.Security.DependencyScanners.Contains(DependencyScanner.OwaspDependencyCheck)) Add(c.Security.NvdApiKeyCredentialId, "Secret text", "NVD API key for OWASP Dependency-Check");
        if (c.Security.DependencyScanners.Contains(DependencyScanner.Snyk)) Add(c.Security.SnykCredentialId, "Secret text", "Snyk API token");
        if (c.AiReview.Enabled) Add(c.AiReview.CredentialId, "Secret text", $"API key for the AI review ({c.AiReview.Provider})");
        foreach (var e in ctx.DeployEnvironments)
        {
            var d = e.Deploy;
            switch (d.Type)
            {
                case DeployTargetType.Helm:
                    Add(d.KubeconfigCredentialId, "Secret file", $"kubeconfig for {e.DisplayName} (namespace-scoped service account)");
                    break;
                case DeployTargetType.DockerSsh:
                    Add(d.SshCredentialId, "SSH username with private key", $"Deploy user on {d.Host}");
                    Add(d.KnownHostsCredentialId, "Secret file", $"known_hosts entry for {d.Host} (ssh-keyscan, verified out of band)");
                    break;
                case DeployTargetType.AzureAppService:
                    Add(d.AzureCredentialId, "Azure Service Principal", $"Deploy to {d.AppName} ({e.DisplayName}), scoped to {d.ResourceGroup}");
                    break;
            }
        }
        return list;
    }

    public static string Pipeline(GenerationContext ctx, IReadOnlyList<string> files)
    {
        var c = ctx.Config;
        var sb = new StringBuilder();
        sb.AppendLine($"# Pipeline for {c.Name}").AppendLine();
        sb.AppendLine("Generated by PipelineForge. Regenerate rather than hand-editing the Jenkinsfile where possible; environment values can be edited in `jenkins/config/environments.yaml`.").AppendLine();

        sb.AppendLine("## Files").AppendLine();
        sb.AppendLine("| File | Purpose |").AppendLine("|---|---|");
        foreach (var f in files) sb.AppendLine($"| `{f}` | {Describe(f)} |");
        sb.AppendLine();

        sb.AppendLine("## Branches and environments").AppendLine();
        sb.AppendLine("Every branch and pull request runs the CI stage (build, tests and the enabled scans).").AppendLine();
        if (c.Environments.Count > 0)
        {
            sb.AppendLine("| Environment | Branch | Deploy | Approval | DAST |").AppendLine("|---|---|---|---|---|");
            foreach (var e in c.Environments)
                sb.AppendLine($"| {e.DisplayName} (`{e.Key}`) | `{e.BranchPattern}` | {SupportFilesWriter.TypeKey(e.Deploy.Type)} | {(e.RequiresApproval ? $"yes, by `{c.Compliance.ApproverGroup}`" : "no")} | {(ctx.HasDast && c.Security.Dast.Environments.Contains(e.Key) ? c.Security.Dast.Mode.ToString() : "-")} |");
            sb.AppendLine();
        }

        sb.AppendLine("## Stages").AppendLine();
        var s = c.Security;
        if (s.SecretScan) sb.AppendLine("- **Secret scan**: Gitleaks over the git history, redacted SARIF report.");
        sb.AppendLine($"- **Build & test**: {string.Join(", ", c.Modules.Select(m => $"`{m.Name}` ({m.Ecosystem})"))}{(c.Modules.Count > 1 ? ", in parallel" : "")}.");
        if (c.Quality.Enabled) sb.AppendLine($"- **{c.Quality.Platform} analysis**{(c.Quality.WaitForQualityGate ? " and **quality gate**" : "")}: project `{c.Quality.ProjectKey}` on the Jenkins installation `{c.Quality.ServerName}`.");
        if (s.DependencyScanners.Count > 0) sb.AppendLine($"- **Dependency scan**: {string.Join(", ", s.DependencyScanners)}; fails on {s.FailOnSeverity} or higher after all scanners ran.");
        if (s.Sbom) sb.AppendLine("- **SBOM**: CycloneDX (`reports/sbom.cdx.json`).");
        if (s.LicenseCheck) sb.AppendLine("- **License check**: Trivy license scanner.");
        if (s.IacScan) sb.AppendLine("- **IaC scan**: Trivy misconfiguration scan (Dockerfiles, Kubernetes, Helm, Terraform).");
        if (c.AiReview.Enabled) sb.AppendLine($"- **AI security review**: {c.AiReview.Provider} `{c.AiReview.Model}` reviews the redacted diff{(c.AiReview.PullRequestsOnly ? " of pull requests" : "")}; {(c.AiReview.FailOnFindings ? $"fails on {c.AiReview.MinSeverity} or higher" : "advisory only")}.");
        foreach (var cs in c.CustomStages) sb.AppendLine($"- **{cs.Name}**: custom steps ({cs.Origin}). Review them: they are inserted as written.");
        if (ctx.ImageModules.Count > 0)
        {
            sb.AppendLine($"- **Build image**: {(ctx.IsKubernetes ? "Kaniko (no Docker daemon)" : "Docker")} builds to a tarball; nothing is pushed yet.");
            if (s.ContainerScan) sb.AppendLine("- **Container scan**: Trivy scans the tarball before it is pushed.");
            if (ctx.DeployEnvironments.Count > 0) sb.AppendLine("- **Push image**: only on deploy branches, tagged `<branch>-<build>-<commit>`.");
        }
        foreach (var e in ctx.DeployEnvironments)
            sb.AppendLine($"- **Deploy {e.DisplayName}**{(e.RequiresApproval ? " (after approval)" : "")}: {SupportFilesWriter.TypeKey(e.Deploy.Type)}{(e.Url is not null ? ", then a smoke test" : "")}.");
        sb.AppendLine();

        sb.AppendLine("## Jenkins setup").AppendLine();
        sb.AppendLine("Create a **Multibranch Pipeline** job pointing at this repository (Bitbucket or GitHub branch source). For PR builds, prefer the *merge with target branch* strategy: the AI review then sees exactly the PR diff.").AppendLine();
        sb.AppendLine("### Plugins").AppendLine();
        foreach (var p in RequiredPlugins(ctx)) sb.AppendLine($"- {p}");
        sb.AppendLine();
        sb.AppendLine("### Credentials").AppendLine();
        sb.AppendLine("Create these in a folder-scoped credentials store, never at system level. Grant each the least privilege it needs.").AppendLine();
        var creds = RequiredCredentials(ctx);
        if (creds.Count == 0) sb.AppendLine("None.");
        else
        {
            sb.AppendLine("| ID | Kind | Purpose |").AppendLine("|---|---|---|");
            foreach (var cr in creds) sb.AppendLine($"| `{cr.Id}` | {cr.Kind} | {cr.Purpose} |");
        }
        sb.AppendLine();
        if (c.Quality.Enabled)
            sb.AppendLine($"Configure the SonarQube installation `{c.Quality.ServerName}` under *Manage Jenkins → System* with its token, and a webhook from Sonar back to `<jenkins>/sonarqube-webhook/` so the quality gate can report.").AppendLine();

        sb.AppendLine("## Notes").AppendLine();
        sb.AppendLine("- Tool images are pinned in `jenkins/agents/*.yaml`" + (ctx.IsKubernetes ? "" : " and `jenkins/stages/common.groovy`") + "; update them regularly.");
        sb.AppendLine("- Shell steps never interpolate values in Groovy; settings reach the shell as environment variables.");
        sb.AppendLine("- Caches and temporary credentials are kept in `<workspace>@tmp/ci`, outside the workspace and the archived reports.");
        if (s.DependencyScanners.Contains(DependencyScanner.OwaspDependencyCheck))
            sb.AppendLine("- OWASP Dependency-Check downloads the NVD database on each build. Mount a persistent volume at the data directory to speed it up.");
        if (c.Modules.Any(m => m.Ecosystem is Ecosystem.Pnpm or Ecosystem.Yarn))
            sb.AppendLine("- pnpm and Yarn run through Corepack, which ships with Node.js up to version 24.");
        if (ctx.DeployEnvironments.Any(e => e.Deploy.Type == DeployTargetType.DockerSsh))
            sb.AppendLine("- Docker hosts must be logged in to the registry once (`docker login`); the pipeline never copies registry credentials to them. Services bind to 127.0.0.1; put a reverse proxy with TLS in front.");
        if (ctx.DeployEnvironments.Any(e => e.Deploy.Type == DeployTargetType.AzureAppService))
            sb.AppendLine("- App Service pulls images with its managed identity (AcrPull) or configured registry credentials.");
        if (c.CustomStages.Count > 0)
            sb.AppendLine("- Custom stages are inserted verbatim and are not checked by PipelineForge.");
        return sb.ToString();
    }

    private static string Describe(string path) => path switch
    {
        "Jenkinsfile" => "Declarative pipeline; orchestrates the stages",
        "jenkins/config/environments.yaml" => "DTAP environments, branches and deploy settings",
        "jenkins/agents/ci-pod.yaml" => "Kubernetes pod for CI (one container per tool)",
        "jenkins/agents/deploy-pod.yaml" => "Kubernetes pod for deploy and DAST",
        "jenkins/stages/common.groovy" => "Shared helpers: init, tool containers, reports",
        "jenkins/stages/build.groovy" => "Build and unit tests per module",
        "jenkins/stages/quality.groovy" => "Sonar analysis and quality gate",
        "jenkins/stages/security.groovy" => "Secret, dependency, SBOM, license and IaC scans",
        "jenkins/stages/deploy.groovy" => "Image build, scan, push and deploy per environment",
        "jenkins/stages/dast.groovy" => "OWASP ZAP scan of a deployed environment",
        "jenkins/stages/ai-review.groovy" => "AI security review step",
        "jenkins/scripts/ai_review.py" => "Redacts the diff and calls the AI provider",
        "sonar-project.properties" => "SonarScanner settings",
        "security/.gitleaks.toml" => "Gitleaks rules and allowlist",
        "security/.trivyignore" => "Accepted vulnerabilities, with reasons and expiry",
        "security/dependency-check-suppressions.xml" => "Dependency-Check suppressions",
        "security/zap-rules.tsv" => "ZAP rule levels",
        "docs/PIPELINE.md" => "This document",
        "docs/iso27001-evidence.md" => "ISO 27001 control mapping",
        _ when path.StartsWith("deploy/helm/values-") => "Helm values per environment",
        _ when path.StartsWith("deploy/helm/chart/") => "Minimal Helm chart",
        _ when path.StartsWith("deploy/docker/") => "Docker Compose file per environment",
        _ => "",
    };

    public static string IsoEvidence(GenerationContext ctx)
    {
        var c = ctx.Config;
        var sb = new StringBuilder();
        sb.AppendLine($"# ISO/IEC 27001:2022 evidence for {c.Name}").AppendLine();
        sb.AppendLine("This pipeline implements the technical part of the controls below. Every build archives its reports (fingerprinted) as evidence. Organisational measures (policies, access reviews, approver lists) stay with you.").AppendLine();
        sb.AppendLine("| Control | Title | How this pipeline implements it |").AppendLine("|---|---|---|");
        foreach (var ctl in ComplianceEnforcer.Iso27001Controls) sb.AppendLine($"| {ctl.Id} | {ctl.Title} | {ctl.Implementation} |");
        sb.AppendLine().AppendLine("## Evidence per build").AppendLine();
        sb.AppendLine("| Report | Location |").AppendLine("|---|---|");
        if (c.Security.SecretScan) sb.AppendLine("| Secret scan | `reports/gitleaks.sarif` |");
        foreach (var s in c.Security.DependencyScanners)
            sb.AppendLine(s switch
            {
                DependencyScanner.TrivyFs => "| Dependency scan (Trivy) | `reports/trivy-fs.sarif` |",
                DependencyScanner.OwaspDependencyCheck => "| Dependency scan (OWASP) | `reports/dependency-check/` |",
                DependencyScanner.OsvScanner => "| Dependency scan (OSV) | `reports/osv.sarif` |",
                DependencyScanner.Snyk => "| Dependency scan (Snyk) | `reports/snyk.sarif` |",
                _ => "| npm audit | build log |",
            });
        if (c.Security.Sbom) sb.AppendLine("| SBOM | `reports/sbom.cdx.json` |");
        if (c.Security.IacScan) sb.AppendLine("| IaC scan | `reports/trivy-iac.sarif` |");
        if (c.Security.ContainerScan && ctx.ImageModules.Count > 0) sb.AppendLine("| Image scan | `reports/trivy-image-*.sarif` |");
        if (ctx.HasDast) sb.AppendLine("| DAST | `reports/zap-<env>.html` / `.json` |");
        if (c.Quality.Enabled) sb.AppendLine($"| Static analysis | {c.Quality.Platform} project `{c.Quality.ProjectKey}` |");
        if (c.AiReview.Enabled) sb.AppendLine("| AI review | `reports/ai-review.md` / `.sarif` |");
        sb.AppendLine("| Approvals | Jenkins build log of the `Approve …` stage (approver and time) |");
        return sb.ToString();
    }
}
