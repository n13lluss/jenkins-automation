    public static string IsoEvidence(GenerationContext ctx)
    {
        var c = ctx.Config;
        var sb = new StringBuilder();
        sb.AppendLine($"# ISO/IEC 27001:2022 evidence for {c.Name}").AppendLine();
        sb.AppendLine("This pipeline implements the technical part of the controls below. Every build archives its reports (fingerprinted) as evidence. Organisational measures (policies, access reviews, approver lists) stay with you.").AppendLine();
        sb.AppendLine("| Control | Title | How this pipeline implements it |").AppendLine("|---|---|---|");
        foreach (var ctl in ComplianceEnforcer.Iso27001Controls) sb.AppendLine($"| {ctl.Id} | {ctl.Title} | {ctl.Implementation} |");
        sb.AppendLine().AppendLine("## Evidence per build").AppendLine();
        sb.AppendLine("| Report | Location |").AppendLine("|---|---|");
        if (c.Security.SecretScan) sb.AppendLine("| Secret scan | `reports/gitleaks.sarif` |");
        foreach (var s in c.Security.DependencyScanners)
            sb.AppendLine(s switch
            {
                DependencyScanner.TrivyFs => "| Dependency scan (Trivy) | `reports/trivy-fs.sarif` |",
                DependencyScanner.OwaspDependencyCheck => "| Dependency scan (OWASP) | `reports/dependency-check/` |",
                DependencyScanner.OsvScanner => "| Dependency scan (OSV) | `reports/osv.sarif` |",
                DependencyScanner.Snyk => "| Dependency scan (Snyk) | `reports/snyk.sarif` |",
                _ => "| npm audit | build log |",
            });
        if (c.Security.Sbom) sb.AppendLine("| SBOM | `reports/sbom.cdx.json` |");
        if (c.Security.IacScan) sb.AppendLine("| IaC scan | `reports/trivy-iac.sarif` |");
        if (c.Security.ContainerScan && ctx.ImageModules.Count > 0) sb.AppendLine("| Image scan | `reports/trivy-image-*.sarif` |");
        if (ctx.HasDast) sb.AppendLine("| DAST | `reports/zap-<env>.html` / `.json` |");
        if (c.Quality.Enabled) sb.AppendLine($"| Static analysis | {c.Quality.Platform} project `{c.Quality.ProjectKey}` |");
        if (c.AiReview.Enabled) sb.AppendLine("| AI review | `reports/ai-review.md` / `.sarif` |");
