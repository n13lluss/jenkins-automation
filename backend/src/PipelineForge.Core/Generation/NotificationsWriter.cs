using PipelineForge.Core.Model;
using static PipelineForge.Core.Validation.GroovyEscaper;

namespace PipelineForge.Core.Generation;

/// <summary>
/// pfNotify(event, text): Slack, Microsoft Teams (Workflows webhook) and e-mail. Defined next to the pipeline
/// rather than in a loaded stage script, so a build that fails before Init still notifies. None of the
/// channels needs an agent, and a failed notification never changes the build result.
/// </summary>
public static class NotificationsWriter
{
    public static void Method(CodeWriter w, GenerationContext ctx)
    {
        var n = ctx.Config.Notifications;
        w.Line();
        w.Line("// Notifications. Generated by PipelineForge. Runs without an agent; failures are logged, not fatal.");
        w.Block("def pfNotify(String event, String text)", () =>
        {
            w.Line("def message = \"${env.JOB_NAME} #${env.BUILD_NUMBER}: ${text}\\n${env.BUILD_URL}\"");
            if (n.Slack.Enabled)
            {
                var token = n.Slack.TokenCredentialId is { } t ? $", tokenCredentialId: {Quote(t)}" : "";
                TryCatch(w, "Slack", () => w.Line($"slackSend channel: {Quote(n.Slack.Channel)}, color: event == 'failure' ? 'danger' : (event == 'approval' ? 'warning' : 'good'), message: message{token}"));
            }
            if (n.Teams.Enabled)
            {
                TryCatch(w, "Teams", () =>
                {
                    w.Line("def card = [type: 'message', attachments: [[contentType: 'application/vnd.microsoft.card.adaptive', content: [");
                    w.Line("    type: 'AdaptiveCard', version: '1.4', body: [[type: 'TextBlock', text: message, wrap: true]],");
                    w.Line("]]]]");
                    w.Block($"withCredentials([string(credentialsId: {Quote(n.Teams.WebhookCredentialId)}, variable: 'TEAMS_WEBHOOK')])", () =>
                        w.Line("httpRequest url: env.TEAMS_WEBHOOK, httpMode: 'POST', contentType: 'APPLICATION_JSON', requestBody: groovy.json.JsonOutput.toJson(card), quiet: true, validResponseCodes: '200:299'"));
                });
            }
            if (n.Email.Enabled)
            {
                TryCatch(w, "E-mail", () => w.Line($"emailext to: {Quote(string.Join(", ", n.Email.Recipients))}, subject: \"[${{env.JOB_NAME}}] ${{text}}\", body: message, mimeType: 'text/plain'"));
            }
        });
    }

    private static void TryCatch(CodeWriter w, string channel, Action body)
    {
        w.Line("try {");
        w.Indent(body);
        w.Line("} catch (e) {");
        w.Indent(() => w.Line($"echo \"{channel} notification failed: ${{e.message}}\""));
        w.Line("}");
    }

    /// <summary>Pipeline-level post conditions for failure and recovery.</summary>
    public static void Post(CodeWriter w, GenerationContext ctx)
    {
        if (!ctx.Notify(NotifyEvent.Failure) && !ctx.Notify(NotifyEvent.Fixed)) return;
        w.Block("post", () =>
        {
            if (ctx.Notify(NotifyEvent.Failure))
                w.Block("failure", () => w.Block("script", () => w.Line("pfNotify('failure', 'Build failed')")));
            if (ctx.Notify(NotifyEvent.Fixed))
                w.Block("fixed", () => w.Block("script", () => w.Line("pfNotify('fixed', 'Build is back to normal')")));
        });
    }
}
