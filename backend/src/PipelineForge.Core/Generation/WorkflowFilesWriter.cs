    private static string Lower(Enum e) => char.ToLowerInvariant(e.ToString()[0]) + e.ToString()[1..];

    public static string Tickets(GenerationContext ctx)
    {
        var t = ctx.Config.Ticketing;
        var sources = string.Join(",", t.Sources.Select(x => Lower(x)));
        var w = new CodeWriter();
        w.Line("// Generated by PipelineForge. Files deduplicated Jira tickets for findings; never fails the build.").Line();
        w.Lines($$"""
            def file(common, String scope) {
                if (env.CHANGE_ID && !{{(t.PullRequests ? "true" : "false")}}) {
                    echo 'Tickets are not filed for pull request builds.'
                    return
                }
                catchError(buildResult: 'SUCCESS', stageResult: 'SUCCESS', catchInterruptions: false, message: 'Ticketing failed; findings are still in the reports.') {
                    withEnv(["SCOPE=${scope}", {{Quote("MIN_SEVERITY=" + t.MinSeverity.ToString().ToLowerInvariant())}}, {{Quote("MAX_FINDINGS=" + t.MaxPerBuild)}}, {{Quote("SOURCES=" + sources)}}]) {
                        common.inTool('python') {
                            sh 'python3 jenkins/scripts/collect_findings.py'
                        }
                    }
                    def data = readJSON file: 'reports/findings.json'
                    for (f in (data.findings ?: [])) {
                        def fp = common.safe(f.fingerprint, '^[a-f0-9]{16}$', 'finding fingerprint')
                        def source = common.safe(f.source, '^[A-Za-z]+$', 'finding source')
                        def existing = jiraJqlSearch(site: {{Quote(t.JiraSite)}}, jql: "project = {{t.ProjectKey}} AND labels = pf-${fp} AND statusCategory != Done", failOnError: false)
                        if (existing?.successful && (existing.data?.total ?: 0) > 0) {
                            continue
                        }
                        jiraNewIssue(site: {{Quote(t.JiraSite)}}, failOnError: false, issue: [fields: [
                            project: [key: {{Quote(t.ProjectKey)}}],
                            issuetype: [name: {{Quote(t.IssueType)}}],
                            summary: f.summary.toString().take(240),
                            description: f.description.toString().take(30000),
                            labels: ['pipelineforge', "pf-${fp}".toString(), "pf-${source}".toString()],
                        ]])
                    }
                }
            }
            """);
        w.Line().Line("return this");
        return w.ToString();
    }

    public static string ZapAuthPlan(GenerationContext ctx)
    {
        var a = ctx.Config.Security.Dast.Authenticated;
        var l = a.Login;
        var body = l.Format == LoginFormat.Json
            ? $"{{\"{l.UsernameField}\":\"{{%username%}}\",\"{l.PasswordField}\":\"{{%password%}}\"}}"
            : $"{l.UsernameField}={{%username%}}&{l.PasswordField}={{%password%}}";
        var logoutRegex = "${TARGET_URL}" + Regex.Escape(l.LogoutPath) + ".*";
        return $$"""
            # ZAP Automation Framework plan: authenticated two-role scan. Generated by PipelineForge.
            # ${...} values are environment variables set by jenkins/stages/dast.groovy (credentials from Jenkins).
            env:
              contexts:
                - name: app
                  urls:
                    - "${TARGET_URL}"
                  includePaths:
                    - "${TARGET_URL}.*"
                  excludePaths:
                    - {{GroovyEscaperYaml(logoutRegex)}}
                  authentication:
                    method: {{GroovyEscaperYaml(l.Format == LoginFormat.Json ? "json" : "form")}}
                    parameters:
                      loginPageUrl: {{GroovyEscaperYaml("${TARGET_URL}" + l.LoginPath)}}
                      loginRequestUrl: {{GroovyEscaperYaml("${TARGET_URL}" + l.LoginPath)}}
                      loginRequestBody: {{GroovyEscaperYaml(body)}}
                    verification:
                      method: autodetect
