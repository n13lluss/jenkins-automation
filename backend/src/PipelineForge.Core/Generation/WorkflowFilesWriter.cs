    public static string Hadolint(GenerationContext ctx)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Hadolint rules. Generated by PipelineForge.");
        sb.AppendLine("failure-threshold: error");
        sb.AppendLine("override:");
        sb.AppendLine("  error:");
        foreach (var rule in new[] { "DL3002", "DL3006", "DL3007", "DL3026", "DL3020", "DL4006" })
            sb.AppendLine($"    - {rule}");
        var registries = ctx.Config.Security.AllowedBaseRegistries;
        if (registries.Count > 0)
        {
            sb.AppendLine("# Base images may only come from these registries (DL3026).");
            sb.AppendLine("trustedRegistries:");
            foreach (var r in registries) sb.AppendLine($"  - {Yaml(r)}");
        }
        return sb.ToString();
    }

    /// <summary>Kyverno policies: only signed (and attested) images, no :latest, no root.</summary>
    public static string KyvernoPolicies(GenerationContext ctx)
    {
        var c = ctx.Config;
        var namespaces = ctx.DeployEnvironments.Where(e => e.Deploy.Type == DeployTargetType.Helm).Select(e => e.Deploy.Namespace).Distinct().ToList();
        var w = new CodeWriter("  ");
        w.Line("# Admission policies for the cluster. Generated by PipelineForge. Requires Kyverno.")
         .Line("# Create the key secret once: kubectl -n kyverno create secret generic pipelineforge-cosign-pub --from-file=cosign.pub")
         .Line("apiVersion: kyverno.io/v1")
         .Line("kind: ClusterPolicy")
         .Line("metadata:")
         .Line($"  name: {c.Name}-verify-images")
         .Line("spec:")
         .Line("  validationFailureAction: Enforce")
         .Line("  background: false")
         .Line("  webhookTimeoutSeconds: 30")
         .Line("  rules:")
         .Line("    - name: verify-signature")
         .Line("      match:")
         .Line("        any:")
         .Line("          - resources:")
         .Line("              kinds: [Pod]")
         .Line($"              namespaces: [{string.Join(", ", namespaces.Select(Yaml))}]")
         .Line("      verifyImages:")
         .Line("        - imageReferences:");
        foreach (var m in ctx.ImageModules) w.Line($"            - {Yaml($"{c.Registry!.Host}/{m.ImageName}*")}");
        w.Line("          mutateDigest: true")
         .Line("          verifyDigest: true")
         .Line("          required: true")
         .Line("          attestors:")
         .Line("            - entries:")
         .Line("                - keys:")
         .Line("                    secret:")
         .Line("                      name: pipelineforge-cosign-pub")
         .Line("                      namespace: kyverno");
        if (!c.Signing.TransparencyLog)
            w.Line("                    rekor:").Line("                      ignoreTlog: true").Line("                    ctlog:").Line("                      ignoreSCT: true");
        if (ctx.Attestations)
        {
            w.Line("          attestations:");
            foreach (var type in new[] { "https://cyclonedx.org/bom", "https://slsa.dev/provenance/v1" })
            {
                w.Line($"            - type: {type}")
                 .Line("              attestors:")
                 .Line("                - entries:")
                 .Line("                    - keys:")
                 .Line("                        secret:")
                 .Line("                          name: pipelineforge-cosign-pub")
                 .Line("                          namespace: kyverno");
                if (!c.Signing.TransparencyLog)
                    w.Line("                        rekor:").Line("                          ignoreTlog: true").Line("                        ctlog:").Line("                          ignoreSCT: true");
            }
        }
        if (c.ClusterPolicy.DisallowLatestTag || c.ClusterPolicy.RequireRunAsNonRoot)
        {
            w.Line("---")
             .Line("apiVersion: kyverno.io/v1")
             .Line("kind: ClusterPolicy")
             .Line("metadata:")
             .Line($"  name: {c.Name}-pod-security")
             .Line("spec:")
             .Line("  validationFailureAction: Enforce")
             .Line("  background: true")
             .Line("  rules:");
            void Match() => w.Line("      match:").Line("        any:").Line("          - resources:").Line("              kinds: [Pod]")
                .Line($"              namespaces: [{string.Join(", ", namespaces.Select(Yaml))}]");
            if (c.ClusterPolicy.DisallowLatestTag)
            {
                w.Line("    - name: disallow-latest-tag");
                Match();
                w.Line("      validate:")
                 .Line("        message: \"Use an image digest or a fixed tag, not :latest.\"")
                 .Line("        pattern:")
                 .Line("          spec:")
                 .Line("            containers:")
                 .Line("              - image: \"!*:latest\"");
            }
            if (c.ClusterPolicy.RequireRunAsNonRoot)
            {
                w.Line("    - name: require-run-as-non-root");
                Match();
                w.Line("      validate:")
                 .Line("        message: \"Pods must set securityContext.runAsNonRoot: true.\"")
                 .Line("        pattern:")
                 .Line("          spec:")
                 .Line("            securityContext:")
                 .Line("              runAsNonRoot: true");
            }
        }
        return w.ToString();
    }

    /// <summary>Groovy regex for a branch glob (used to enable the cron trigger on one branch only).</summary>
    public static string GlobToRegex(string glob)
    {
        var sb = new StringBuilder("^");
        for (var i = 0; i < glob.Length; i++)
        {
            var ch = glob[i];
            if (ch == '*' && i + 1 < glob.Length && glob[i + 1] == '*') { sb.Append(".*"); i++; }
            else if (ch == '*') sb.Append("[^/]*");
            else sb.Append(Regex.Escape(ch.ToString()));
        }
        return sb.Append('$').ToString();
    }

    public static string ScheduledJenkinsfile(GenerationContext ctx)
    {
        var c = ctx.Config;
        var sch = c.Security.Dast.Schedule;
        var target = c.Environments.First(e => e.Key == sch.Environment);
        var auth = ctx.Authenticated && sch.AuthenticatedDaily;
        var w = new CodeWriter();
        w.Line("// Scheduled security scans of a live environment, independent of code changes. Generated by PipelineForge.")
         .Line("// Run it as a second multibranch job with script path Jenkinsfile.scheduled (PipelineForge can create it).");
        JenkinsfileWriter.Program(w, ctx, ["common", "dast", "tickets"], () => w.Block("pipeline", () =>
        {
            w.Line("agent none");
            w.Block("triggers", () =>
                w.Line($"cron(env.BRANCH_NAME ==~ {Quote(GlobToRegex(target.BranchPattern))} ? {Quote(sch.BaselineCron)} : '')"));
            if (ctx.Authenticated)
                w.Block("parameters", () =>
                    w.Line("booleanParam(name: 'AUTHENTICATED_SCAN', defaultValue: false, description: 'Also run the authenticated two-role scan now')"));
            w.Block("options", () =>
            {
                w.Line($"buildDiscarder(logRotator(numToKeepStr: {Quote(c.Options.BuildsToKeep.ToString())}))");
                w.Line("disableConcurrentBuilds()");
                w.Line("timestamps()");
            });
            w.Block("stages", () =>
                w.Block("stage('Scheduled security scans')", () =>
                {
                    w.Block("when", () =>
                    {
                        w.Line("beforeAgent true");
                        w.Line(GenerationContext.BranchCondition(target.BranchPattern));
                    });
                    JenkinsfileWriter.Agent(w, ctx, "jenkins/agents/deploy-pod.yaml");
                    w.Block("options", () => w.Line("timeout(time: 120, unit: 'MINUTES')"));
                    w.Block("steps", () => w.Block("script", () =>
                    {
                        JenkinsfileWriter.Materialize(w, ctx);
                        w.Line("common = load 'jenkins/stages/common.groovy'");
                        w.Line("dast = load 'jenkins/stages/dast.groovy'");
                        if (ctx.Ticketing) w.Line("tickets = load 'jenkins/stages/tickets.groovy'");
                        w.Line("envs = common.init()");
                        w.Line($"// Passive baseline every run ({sch.BaselineCron}).");
                        w.Block("catchError(buildResult: 'FAILURE', stageResult: 'FAILURE')", () =>
                            w.Line($"dast.baseline(common, envs[{Quote(target.Key)}])"));
                        if (auth)
                        {
                            w.Line("// The first scheduled run of the day (UTC) also runs the authenticated two-role scan.");
                            w.Line("def firstRunToday = sh(returnStdout: true, script: 'date -u +%H').trim().toInteger() < 6");
                            w.Block("if (params.AUTHENTICATED_SCAN || firstRunToday)", () =>
                                w.Line($"dast.authenticatedScan(common, envs[{Quote(c.Security.Dast.Authenticated.Environment)}])"));
                        }
                        else if (ctx.Authenticated)
                        {
                            w.Block("if (params.AUTHENTICATED_SCAN)", () =>
                                w.Line($"dast.authenticatedScan(common, envs[{Quote(c.Security.Dast.Authenticated.Environment)}])"));
                        }
                    }));
                    w.Block("post", () =>
                    {
                        w.Block("always", () => w.Block("script", () =>
                        {
                            w.Line("if (common) { common.publishReports() }");
                            if (ctx.Ticketing) w.Line("if (tickets) { tickets.file(common, 'scheduled') }");
                        }));
                        if (!ctx.IsKubernetes) w.Block("cleanup", () => w.Line("cleanWs()"));
                    });
                }));
        }));
        return w.ToString();
    }
