    public static string MavenSettings(GenerationContext ctx)
    {
        var p = ctx.Proxy!;
        var url = SecurityElement.Escape($"{p.BaseUrl.TrimEnd('/')}/{p.MavenPath!.Trim('/')}");
        return $$"""
            <?xml version="1.0" encoding="UTF-8"?>
            <!-- Generated by PipelineForge. Every Maven request goes through the repository manager ({{p.Type}}).
                 Credentials come from the environment inside common.withProxy(); nothing secret is stored here. -->
            <settings xmlns="http://maven.apache.org/SETTINGS/1.2.0">
              <servers>
                <server>
                  <id>pipelineforge-proxy</id>
                  <username>${env.PROXY_USER}</username>
                  <password>${env.PROXY_PASSWORD}</password>
                </server>
              </servers>
              <mirrors>
                <mirror>
                  <id>pipelineforge-proxy</id>
                  <name>Repository manager</name>
                  <mirrorOf>*</mirrorOf>
                  <url>{{url}}</url>
                </mirror>
              </mirrors>
            </settings>

            """;
    }

