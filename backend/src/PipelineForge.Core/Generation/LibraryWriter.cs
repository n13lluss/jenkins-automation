using PipelineForge.Core.Model;
using static PipelineForge.Core.Validation.GroovyEscaper;

namespace PipelineForge.Core.Generation;

/// <summary>
/// Shared library layout: the pipeline, its stage scripts, helper scripts, agent pods and environment settings
/// move to a protected library repository (files under <see cref="Prefix"/>). The application repository keeps a
/// thin Jenkinsfile plus the files its developers own (Helm chart, ignore lists, docs).
/// </summary>
public static class LibraryWriter
{
    /// <summary>Generated paths starting with this prefix belong in the library repository.</summary>
    public const string Prefix = "library/";

    /// <summary>Security configuration that decides what is checked; kept with the pipeline, not the app.</summary>
    private static readonly HashSet<string> ProtectedSecurityFiles =
    [
        "security/maven-enforcer.xml",
        "security/.hadolint.yaml",
        "security/zap/auth-plan.yaml",
        "security/zap/admin-paths.txt",
    ];

    public static bool IsLibraryOwned(string path) => path.StartsWith("jenkins/", StringComparison.Ordinal) || ProtectedSecurityFiles.Contains(path);

    public static List<GeneratedFile> Split(GenerationContext ctx, List<GeneratedFile> files)
    {
        var c = ctx.Config;
        var result = new List<GeneratedFile>();
        var materialized = new List<string>();
        foreach (var f in files)
        {
            if (f.Path is "Jenkinsfile" or "Jenkinsfile.scheduled")
            {
                var var = f.Path == "Jenkinsfile" ? ctx.LibraryVar : ctx.LibraryVar + "Scheduled";
                result.Add(new(f.Path, ThinJenkinsfile(ctx, var)));
                result.Add(new($"{Prefix}vars/{var}.groovy", f.Content));
            }
            else if (IsLibraryOwned(f.Path))
            {
                result.Add(new($"{Prefix}resources/{ctx.ResourceRoot}/{f.Path}", f.Content));
                // Pod templates are read with libraryResource directly; everything else is written into the workspace.
                if (!f.Path.StartsWith("jenkins/agents/", StringComparison.Ordinal)) materialized.Add(f.Path);
            }
            else
            {
                result.Add(f);
            }
        }
        if (ctx.Signing) materialized.Add(c.Signing.PublicKeyPath);
        result.Add(new($"{Prefix}vars/{ctx.LibraryVar}Files.groovy", FilesVar(ctx, materialized)));
        result.Add(new($"{Prefix}README.md", Readme(ctx)));
        return result;
    }

    private static string ThinJenkinsfile(GenerationContext ctx, string var) =>
        $"""
        // Generated by PipelineForge. The pipeline lives in the protected shared library '{ctx.Config.Library.Name}'
        // (vars/{var}.groovy); changes to it go through a pull request on the library repository.
        @Library({Quote(ctx.Config.Library.Name)}) _

        {var}()

        """;

    private static string FilesVar(GenerationContext ctx, IReadOnlyList<string> paths)
    {
        var w = new CodeWriter();
        w.Line("// Generated by PipelineForge. Writes this pipeline's support files from the library over the workspace,")
         .Line("// so a branch or pull request cannot change the scripts, environments or scan settings that run.")
         .Line();
        w.Block("def call()", () =>
        {
            w.Line("def files = [");
            foreach (var p in paths) w.Line($"    {Quote(p)},");
            w.Line("]");
            w.Block("for (String path in files)", () =>
                w.Line($"writeFile file: path, text: libraryResource({Quote(ctx.ResourceRoot + "/")} + path)"));
        });
        return w.ToString();
    }

    private static string Readme(GenerationContext ctx)
    {
        var c = ctx.Config;
        var lib = c.Library;
        var key = c.Signing.PublicKeyPath;
        return $"""
            # Jenkins shared library: {lib.Name}

            Generated by PipelineForge for the pipeline `{c.Name}`. Copy `vars/` and `resources/` into the library
            repository{(lib.Repository is { } r ? $" (`{r}`)" : "")}; several pipelines can share one library.

            | Path | Purpose |
            | --- | --- |
            | `vars/{ctx.LibraryVar}.groovy` | The declarative pipeline, called from the application's Jenkinsfile |
            | `vars/{ctx.LibraryVar}Files.groovy` | Writes the support files below into the workspace on every agent |
            | `resources/{ctx.ResourceRoot}/` | Stage scripts, helper scripts, agent pods, environments and scan settings |
            {(ctx.Scheduled ? $"| `vars/{ctx.LibraryVar}Scheduled.groovy` | The scheduled security scans |\n" : "")}
            ## Jenkins setup

            1. Register the library as a **folder library** on the folder or multibranch job (PipelineForge does this
               when it creates the job) or as a global library: name `{lib.Name}`, default version `{lib.DefaultVersion}`.
            2. Untick **Allow default version to be overridden**, so a branch cannot load the library from another ref.
            3. Protect `{lib.DefaultVersion}` in the library repository: pull requests with review only.
            4. Discover fork pull requests with trust *contributors with write permission* (GitHub) or *forks in the
               same account* (Bitbucket): untrusted forks then run the target branch's Jenkinsfile.
            {(ctx.Signing ? $"5. Commit the Cosign public key as `resources/{ctx.ResourceRoot}/{key}`; deploys verify against that copy.\n" : "")}
            Folder libraries run in the Groovy sandbox like a Jenkinsfile. Developers with write access to the application
            repository can still edit the thin Jenkinsfile on a branch, so keep deploy credentials in a folder or
            credentials domain that only the protected branches use.
            """;
    }
}
