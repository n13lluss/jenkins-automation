    public static string Compose(GenerationContext ctx, EnvironmentConfig e)
    {
        var w = new CodeWriter("  ");
        w.Line($"# Docker Compose for {e.DisplayName}. Generated by PipelineForge.")
         .Line("# Copied to the host by the pipeline; IMAGE_TAG is exported by the deploy step.")
         .Line("services:");
        var port = 8080;
        foreach (var m in ctx.ImageModules)
        {
            w.Line($"  {StageScriptsWriter.HelmKey(m.Name)}:");
            var reference = $"{ctx.Config.Registry!.Host}/{m.ImageName}@${{{GenerationContext.DigestVar(m)}:?the image digest is set by the pipeline}}";
            w.Line($"    image: {Yaml(reference)}");
            w.Line("    restart: unless-stopped");
            w.Line("    read_only: true");
            w.Line("    security_opt: [\"no-new-privileges:true\"]");
            w.Line("    cap_drop: [\"ALL\"]");
            w.Line($"    ports: [\"127.0.0.1:{port}:8080\"]");
            port++;
        }
        return w.ToString();
    }
