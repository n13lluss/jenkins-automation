    public static string ZapRules(GenerationContext ctx)
    {
        var failLevel = ctx.IsIso ? "FAIL" : "WARN";
        return $"""
            # OWASP ZAP rule configuration (tab separated: id, IGNORE|INFO|WARN|FAIL, name). Generated by PipelineForge.
            # Rules not listed use the scan default (WARN). FAIL rules fail the DAST stage.
            10010	{failLevel}	(Cookie No HttpOnly Flag)
            10011	{failLevel}	(Cookie Without Secure Flag)
            10035	{failLevel}	(Strict-Transport-Security Header Not Set)
            10038	WARN	(Content Security Policy (CSP) Header Not Set)
            10096	IGNORE	(Timestamp Disclosure)
            40012	FAIL	(Cross Site Scripting (Reflected))
            40018	FAIL	(SQL Injection)

            """;
    }

    public static string HelmValues(GenerationContext ctx, EnvironmentConfig e)
    {
        var w = new CodeWriter("  ");
        w.Line($"# Helm values for {e.DisplayName}. Generated by PipelineForge.")
         .Line("# images.<name>.tag is set by the pipeline (--set-string).");
        var isProd = e.RequiresApproval;
        w.Line($"replicaCount: {(isProd ? 2 : 1)}");
        w.Line("images:");
        foreach (var m in ctx.ImageModules)
        {
            w.Line($"  {StageScriptsWriter.HelmKey(m.Name)}:");
            w.Line($"    repository: {Yaml($"{ctx.Config.Registry!.Host}/{m.ImageName}")}");
            w.Line("    tag: \"\"");
            w.Line("    port: 8080");
        }
        w.Line("resources:");
        w.Line($"  requests: {{ cpu: \"100m\", memory: \"{(isProd ? "256Mi" : "128Mi")}\" }}");
        w.Line($"  limits: {{ memory: \"{(isProd ? "1Gi" : "512Mi")}\" }}");
        if (e.AppSecrets is { } sec)
        {
            w.Line("# Application secrets: External Secrets Operator copies these keys from the store into a Secret.");
            w.Line("externalSecret:");
            w.Line("  enabled: true");
            w.Line($"  storeName: {Yaml(sec.StoreName)}");
            w.Line($"  storeKind: {Yaml(sec.StoreKind.ToString())}");
            w.Line($"  refreshInterval: {Yaml(sec.RefreshInterval)}");
            w.Line("  data:");
            foreach (var k in sec.Keys)
            {
                w.Line($"    - secretKey: {Yaml(k.Name)}");
                w.Line($"      remoteKey: {Yaml(k.RemoteKey)}");
                if (k.Property is not null) w.Line($"      property: {Yaml(k.Property)}");
            }
        }
        return w.ToString();
    }

