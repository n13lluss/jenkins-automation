    public static string PodTemplate(GenerationContext ctx, IReadOnlyDictionary<string, string> containers, string purpose)
    {
        var w = new CodeWriter("  ");
        w.Line($"# {purpose} agent pod. Generated by PipelineForge; used by the Kubernetes plugin (yamlFile).");
        w.Line("apiVersion: v1").Line("kind: Pod");
        w.Block("metadata:", () => w.Block("labels:", () => w.Line("app.kubernetes.io/managed-by: pipelineforge"), "", ""), "", "");
        w.Block("spec:", () =>
        {
            w.Line("automountServiceAccountToken: false");
            w.Block("securityContext:", () => w.Block("seccompProfile:", () => w.Line("type: RuntimeDefault"), "", ""), "", "");
            w.Line("containers:");
            foreach (var (name, image) in containers)
            {
                var distroless = name is "kaniko" or "crane";
                w.Line($"  - name: {name}");
                w.Indent(() => w.Indent(() =>
                {
                    w.Line($"image: {Yaml(image)}");
                    w.Line(distroless ? "command: [\"/busybox/cat\"]" : "command: [\"cat\"]");
                    w.Line("tty: true");
                    var heavy = name is "dependency-check" or "kaniko" || !ToolImages.Tools.ContainsKey(name);
                    w.Line("resources:");
                    w.Line($"  requests: {{ cpu: \"{(heavy ? "500m" : "100m")}\", memory: \"{(heavy ? "1Gi" : "256Mi")}\" }}");
                    w.Line($"  limits: {{ memory: \"{(heavy ? "4Gi" : "1Gi")}\" }}");
                    if (name != "kaniko")
                    {
                        w.Line("securityContext:");
                        w.Line("  allowPrivilegeEscalation: false");
                    }
                }));
            }
        }, "", "");
        return w.ToString();
    }

    public static string EnvironmentsYaml(GenerationContext ctx)
    {
        var c = ctx.Config;
        var w = new CodeWriter("  ");
        w.Line("# DTAP environments. Generated by PipelineForge; read at runtime by jenkins/stages/common.groovy.")
         .Line("# Values are validated again at runtime: keep to letters, digits and . _ - / characters.")
         .Line("environments:");
        if (c.Environments.Count == 0) w.Line("  []");
        foreach (var e in c.Environments)
        {
            var d = e.Deploy;
            w.Line($"  - key: {Yaml(e.Key)}");
            w.Indent(() => w.Indent(() =>
            {
                w.Line($"name: {Yaml(e.DisplayName)}");
                w.Line($"branch: {Yaml(e.BranchPattern)}");
                if (e.Url is not null) w.Line($"url: {Yaml(e.Url)}");
                w.Line($"approval: {(e.RequiresApproval ? "true" : "false")}");
                if (e.PromoteFrom is not null) w.Line($"promoteFrom: {Yaml(e.PromoteFrom)}");
                w.Line($"rollback: {(e.RollbackOnFailure ? "true" : "false")}");
                w.Block("health:", () =>
                {
                    w.Line($"path: {Yaml(e.Health.Path)}");
                    w.Line($"status: {e.Health.ExpectedStatus}");
                    w.Line($"successes: {e.Health.Successes}");
                    w.Line($"timeout: {e.Health.TimeoutSeconds}");
                }, "", "");
                if (e.Database is { } db && ctx.Migrations)
                    w.Block("database:", () =>
                    {
                        w.Line($"jdbcUrl: {Yaml(db.JdbcUrl)}");
                        w.Line($"credentialId: {Yaml(db.CredentialId)}");
                    }, "", "");
                w.Line($"type: {Yaml(TypeKey(d.Type))}");
                switch (d.Type)
                {
                    case DeployTargetType.Helm:
                        w.Block("helm:", () =>
                        {
                            w.Line($"kubeconfigCredentialId: {Yaml(d.KubeconfigCredentialId)}");
                            w.Line($"namespace: {Yaml(d.Namespace)}");
                            w.Line($"release: {Yaml(d.ReleaseName)}");
                            w.Line($"chart: {Yaml(d.ChartPath)}");
                        }, "", "");
                        break;
                    case DeployTargetType.DockerSsh:
                        w.Block("ssh:", () =>
                        {
                            w.Line($"credentialId: {Yaml(d.SshCredentialId)}");
                            w.Line($"knownHostsCredentialId: {Yaml(d.KnownHostsCredentialId)}");
                            w.Line($"host: {Yaml(d.Host)}");
                            w.Line($"user: {Yaml(d.User)}");
                            w.Line($"dir: {Yaml(d.RemoteDir)}");
                        }, "", "");
                        break;
                    case DeployTargetType.AzureAppService:
                        w.Block("azure:", () =>
                        {
                            w.Line($"credentialId: {Yaml(d.AzureCredentialId)}");
                            w.Line($"resourceGroup: {Yaml(d.ResourceGroup)}");
                            w.Line($"app: {Yaml(d.AppName)}");
                            if (d.Slot is not null) w.Line($"slot: {Yaml(d.Slot)}");
                            w.Line($"image: {Yaml(ctx.ImageModules.FirstOrDefault()?.ImageName ?? "")}");
                        }, "", "");
                        break;
                }
            }));
        }
        return w.ToString();
    }

    public static string TypeKey(DeployTargetType t) => t switch
    {
        DeployTargetType.Helm => "helm",
        DeployTargetType.DockerSsh => "docker-ssh",
        DeployTargetType.AzureAppService => "azure-app-service",
        _ => "none",
    };

    public static string SonarProperties(GenerationContext ctx)
    {
        var c = ctx.Config;
        var q = c.Quality;
        var lines = new List<string>
        {
            "# SonarScanner settings. Generated by PipelineForge.",
            "# Server URL and token come from withSonarQubeEnv in Jenkins, never from this file.",
            $"sonar.projectKey={Property(q.ProjectKey)}",
            $"sonar.projectName={Property(c.Name)}",
        };
        if (q.Platform == QualityPlatform.SonarCloud && q.Organization is not null)
            lines.Add($"sonar.organization={Property(q.Organization)}");
        lines.Add("sonar.sourceEncoding=UTF-8");
        lines.Add("sonar.sources=" + string.Join(",", c.Modules.Select(m => Property(m.Path)).Distinct()));
        lines.Add("sonar.exclusions=**/node_modules/**,**/target/**,**/build/**,**/bin/**,**/obj/**,**/vendor/**,**/dist/**,reports/**");

        string P(ModuleConfig m, string rel) => Property(m.Path == "." ? rel : $"{m.Path}/{rel}");
        var javaBinaries = c.Modules.Where(m => m.Ecosystem == Ecosystem.Maven).Select(m => P(m, "target/classes"))
            .Concat(c.Modules.Where(m => m.Ecosystem == Ecosystem.Gradle).Select(m => P(m, "build/classes")))
            .ToList();
        if (javaBinaries.Count > 0) lines.Add("sonar.java.binaries=" + string.Join(",", javaBinaries));
        var jacoco = c.Modules.Where(m => m.Ecosystem == Ecosystem.Maven).Select(m => P(m, "target/site/jacoco/jacoco.xml"))
            .Concat(c.Modules.Where(m => m.Ecosystem == Ecosystem.Gradle).Select(m => P(m, "build/reports/jacoco/test/jacocoTestReport.xml")))
            .ToList();
        if (jacoco.Count > 0) lines.Add("sonar.coverage.jacoco.xmlReportPaths=" + string.Join(",", jacoco));
        var lcov = c.Modules.Where(m => m.Ecosystem is Ecosystem.Npm or Ecosystem.Pnpm or Ecosystem.Yarn).Select(m => P(m, "coverage/lcov.info")).ToList();
        if (lcov.Count > 0) lines.Add("sonar.javascript.lcov.reportPaths=" + string.Join(",", lcov));
        var py = c.Modules.Where(m => m.Ecosystem == Ecosystem.Python).Select(m => P(m, "coverage.xml")).ToList();
        if (py.Count > 0) lines.Add("sonar.python.coverage.reportPaths=" + string.Join(",", py));
        var go = c.Modules.Where(m => m.Ecosystem == Ecosystem.Go).Select(m => P(m, "coverage.out")).ToList();
        if (go.Count > 0) lines.Add("sonar.go.coverage.reportPaths=" + string.Join(",", go));
        if (c.Modules.Any(m => m.Ecosystem == Ecosystem.DotNet))
            lines.Add("# Note: C# needs the SonarScanner for .NET; with mixed modules only the other languages are analysed here.");
        return string.Join("\n", lines) + "\n";
    }

