                                        az webapp config container set --resource-group "$DEPLOY_RG" --name "$DEPLOY_APP" --container-image-name "$REGISTRY/$DEPLOY_IMAGE:$IMAGE_TAG" --output none
                                        az webapp restart --resource-group "$DEPLOY_RG" --name "$DEPLOY_APP"
