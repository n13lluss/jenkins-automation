                        {{Quote("AI_PROVIDER=" + provider)}},
                        {{Quote("AI_MODEL=" + ai.Model)}},
                        {{Quote("AI_BASE_URL=" + (ai.BaseUrl ?? ""))}},
                        {{Quote("AI_FAIL_ON_FINDINGS=" + (ai.FailOnFindings ? "true" : "false"))}},
                        {{Quote("AI_MIN_SEVERITY=" + ai.MinSeverity.ToString().ToLowerInvariant())}},
