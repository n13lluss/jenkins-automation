using PipelineForge.Core.Model;
using static PipelineForge.Core.Validation.GroovyEscaper;

namespace PipelineForge.Core.Generation;

/// <summary>
/// Writes the declarative Jenkinsfile. It only orchestrates: stage logic lives in
/// jenkins/stages/*.groovy and environment settings in jenkins/config/environments.yaml.
/// </summary>
public static class JenkinsfileWriter
{
    public static string Write(GenerationContext ctx)
    {
        var c = ctx.Config;
        var w = new CodeWriter();
        w.Line("// Generated by PipelineForge. See docs/PIPELINE.md for required plugins and credentials.")
         .Line("// Stage logic: jenkins/stages/*.groovy · Environments: jenkins/config/environments.yaml");
        Program(w, ctx, ["common", "ci", "quality", "security", "delivery", "dast", "aiReview", "tickets"], () => w.Block("pipeline", () =>
        {
            w.Line("agent none");
            w.Block("options", () =>
            {
                w.Line($"buildDiscarder(logRotator(numToKeepStr: {Quote(c.Options.BuildsToKeep.ToString())}, artifactNumToKeepStr: {Quote(c.Options.BuildsToKeep.ToString())}))");
                if (c.Options.DisableConcurrentBuilds) w.Line("disableConcurrentBuilds()");
                w.Line("timestamps()");
            });
            w.Block("environment", () =>
            {
                w.Line($"APP_NAME = {Quote(c.Name)}");
                if (c.Registry is { } reg) w.Line($"REGISTRY = {Quote(reg.Host)}");
            });
            w.Block("stages", () =>
            {
                WriteCiStage(w, ctx);
                foreach (var e in c.Environments.Where(e => e.Deploy.Type != DeployTargetType.None))
                    WriteEnvironmentStages(w, ctx, e);
            });
            NotificationsWriter.Post(w, ctx);
        }));
        return w.ToString();
    }

    /// <summary>
    /// The script around the pipeline block: script variables in a Jenkinsfile, or @Field variables and a
    /// call() method in a shared library global variable.
    /// </summary>
    internal static void Program(CodeWriter w, GenerationContext ctx, IReadOnlyList<string> modules, Action pipeline)
    {
        w.Line();
        if (!ctx.Library)
        {
            w.Line($"def {string.Join(", ", modules)}").Line("def envs = [:]").Line();
            pipeline();
        }
        else
        {
            w.Line("import groovy.transform.Field").Line();
            foreach (var m in modules) w.Line($"@Field def {m}");
            w.Line("@Field def envs = [:]").Line();
            w.Block("def call()", pipeline);
        }
        if (ctx.Notifications) NotificationsWriter.Method(w, ctx);
    }

    /// <summary>
    /// In the shared library layout, writes the library's copies of the support files over the workspace
    /// before anything on a new agent reads them, so a branch cannot change scripts or environments.
    /// </summary>
    internal static void Materialize(CodeWriter w, GenerationContext ctx)
    {
        if (ctx.Library) w.Line($"{ctx.LibraryVar}Files()");
    }

    internal static void Agent(CodeWriter w, GenerationContext ctx, string podFile)
    {
        w.Block("agent", () =>
        {
            if (ctx.IsKubernetes)
            {
                w.Block("kubernetes", () =>
                {
                    if (ctx.Config.Agent.KubernetesCloud is { } cloud) w.Line($"cloud {Quote(cloud)}");
                    w.Line(ctx.Library
                        ? $"yaml libraryResource({Quote($"{ctx.ResourceRoot}/{podFile}")})"
                        : $"yamlFile {Quote(podFile)}");
                });
            }
            else
            {
                w.Line($"label {Quote(ctx.Config.Agent.DockerLabel)}");
            }
        });
    }

    private static void ScriptStage(CodeWriter w, string name, string call, string? when = null, Action? post = null)
    {
        w.Block($"stage({Quote(name)})", () =>
        {
            if (when is not null) w.Block("when", () => w.Line(when));
            w.Block("steps", () => w.Block("script", () => w.Line(call)));
            if (post is not null) w.Block("post", post);
        });
    }

    private static void WriteCiStage(CodeWriter w, GenerationContext ctx)
    {
        var c = ctx.Config;
        var s = c.Security;
        w.Block("stage('CI')", () =>
        {
            Agent(w, ctx, "jenkins/agents/ci-pod.yaml");
            w.Block("options", () => w.Line($"timeout(time: {c.Options.TimeoutMinutes}, unit: 'MINUTES')"));
            w.Block("stages", () =>
            {
                w.Block("stage('Init')", () => w.Block("steps", () => w.Block("script", () =>
                {
                    Materialize(w, ctx);
                    w.Line("common = load 'jenkins/stages/common.groovy'");
                    w.Line("ci = load 'jenkins/stages/build.groovy'");
                    if (c.Quality.Enabled) w.Line("quality = load 'jenkins/stages/quality.groovy'");
                    w.Line("security = load 'jenkins/stages/security.groovy'");
                    if (ctx.ImageModules.Count > 0 || ctx.DeployEnvironments.Count > 0) w.Line("delivery = load 'jenkins/stages/deploy.groovy'");
                    if (HasDynamicTests(ctx)) w.Line("dast = load 'jenkins/stages/dast.groovy'");
                    if (c.AiReview.Enabled) w.Line("aiReview = load 'jenkins/stages/ai-review.groovy'");
                    if (ctx.Ticketing) w.Line("tickets = load 'jenkins/stages/tickets.groovy'");
                    w.Line("envs = common.init()");
                })));

                // Runs on every build so expired or unowned exceptions fail fast, before any scan uses them.
                if (ctx.Exceptions) ScriptStage(w, "Exception review", "common.applyExceptions()");
                var checks = ctx.TriggerCondition(c.Triggers.Checks);
                var package = ctx.TriggerCondition(c.Triggers.Package);
                if (ctx.Pinning) ScriptStage(w, "Dependency pinning", "security.dependencyPinning(common)");
                if (s.SecretScan) ScriptStage(w, "Secret scan", "security.secretScan(common)", when: checks);
                ScriptStage(w, "Build & test", "ci.buildAndTest(common)", post: () =>
                    w.Block("always", () => w.Block("script", () => w.Line("ci.publishTests()"))));
                if (c.Quality.Enabled)
                {
                    ScriptStage(w, c.Quality.Platform == QualityPlatform.SonarCloud ? "SonarCloud analysis" : "SonarQube analysis", "quality.analyse(common)", when: checks);
                    if (c.Quality.WaitForQualityGate) ScriptStage(w, "Quality gate", "quality.gate(common)", when: checks);
                }
                if (ctx.HasDependencyStage) ScriptStage(w, "Dependency scan", "security.dependencyScan(common)", when: checks);
                if (s.Sbom) ScriptStage(w, "SBOM", "security.sbom(common)", when: checks);
                if (s.LicenseCheck) ScriptStage(w, "License check", "security.licenseCheck(common)", when: checks);
                if (s.IacScan) ScriptStage(w, "IaC scan", "security.iacScan(common)", when: checks);
                if (ctx.DockerfileLint) ScriptStage(w, "Dockerfile lint", "security.dockerfileLint(common)", when: checks);
                if (c.AiReview.Enabled)
                    ScriptStage(w, "AI security review", "aiReview.review(common)", when: c.AiReview.PullRequestsOnly ? "changeRequest()" : null);

                foreach (var cs in c.CustomStages)
                {
                    w.Block($"stage({Quote(cs.Name)})", () =>
                    {
                        w.Line(cs.Origin == CustomStageOrigin.Imported
                            ? "// Imported from the original Jenkinsfile. Review before use."
                            : "// Custom stage added in PipelineForge. Review before use.");
                        w.Block("steps", () => w.Lines(cs.Steps.Length == 0 ? "echo 'TODO'" : cs.Steps));
                    });
                }

                if (ctx.ImageModules.Count > 0)
                {
                    ScriptStage(w, "Build image", "delivery.buildImages(common)", when: package);
                    if (s.ContainerScan) ScriptStage(w, "Container scan", "delivery.scanImages(common)", when: package);
                    if (ctx.Ephemeral) ScriptStage(w, "Ephemeral DAST", "dast.ephemeralScan(common)", when: package);
                    if (ctx.DeployEnvironments.Count > 0)
                    {
                        ScriptStage(w, "Push image", "delivery.pushImages(common)", when: ctx.DeployBranchesCondition());
                        if (ctx.Signing) ScriptStage(w, "Sign image", "delivery.signImages(common)", when: ctx.DeployBranchesCondition());
                    }
                }
            });
            w.Block("post", () =>
            {
                w.Block("always", () => w.Block("script", () =>
                {
                    w.Line("if (common) { common.publishReports() }");
                    if (ctx.Ticketing) w.Line("if (tickets) { tickets.file(common, 'ci') }");
                }));
                if (!ctx.IsKubernetes) w.Block("cleanup", () => w.Line("cleanWs()"));
            });
        });
    }

    private static void WriteEnvironmentStages(CodeWriter w, GenerationContext ctx, EnvironmentConfig e)
    {
        var c = ctx.Config;
        var when = GenerationContext.BranchCondition(e.BranchPattern);
        var envRef = $"envs[{Quote(e.Key)}]";

        var a = c.Security.Dast.Authenticated;
        if (ctx.Authenticated && a.BeforeProduction && Compliance.ComplianceEnforcer.IsProduction(e))
            VerifyStage(w, ctx, $"Authenticated scan before {e.DisplayName}", when, $"dast.authenticatedScan(common, envs[{Quote(a.Environment)}])", tickets: true);

        if (e.RequiresApproval)
        {
            w.Block($"stage({Quote("Approve " + e.DisplayName)})", () =>
            {
                w.Block("when", () => w.Line(when));
                w.Block("options", () => w.Line("timeout(time: 72, unit: 'HOURS')"));
                w.Block("steps", () =>
                {
                    var submitter = c.Compliance.ApproverGroup;
                    if (ctx.Notify(NotifyEvent.Approval))
                        w.Block("script", () => w.Line($"pfNotify('approval', {Quote($"Waiting for approval to deploy to {e.DisplayName}")})"));
                    w.Line($"input message: {Quote($"Deploy {c.Name} to {e.DisplayName}?")}, ok: 'Deploy', submitter: {Quote(submitter)}");
                });
            });
        }

        w.Block($"stage({Quote("Deploy " + e.DisplayName)})", () =>
        {
            w.Block("when", () => { w.Line("beforeAgent true"); w.Line(when); });
            Agent(w, ctx, "jenkins/agents/deploy-pod.yaml");
            w.Block("options", () => w.Line("timeout(time: 30, unit: 'MINUTES')"));
            w.Block("steps", () => w.Block("script", () =>
            {
                Materialize(w, ctx);
                w.Line($"delivery.deploy(common, {envRef})");
            }));
            var notifyDeployed = ctx.Notify(NotifyEvent.ProductionDeployed) && Compliance.ComplianceEnforcer.IsProduction(e);
            if (notifyDeployed || !ctx.IsKubernetes)
                w.Block("post", () =>
                {
                    if (notifyDeployed)
                        w.Block("success", () => w.Block("script", () => w.Line($"pfNotify('deployed', {Quote($"Deployed {c.Name} to {e.DisplayName}")})")));
                    if (!ctx.IsKubernetes) w.Block("cleanup", () => w.Line("cleanWs()"));
                });
        });

        if (ctx.HasDast && c.Security.Dast.Environments.Contains(e.Key))
            VerifyStage(w, ctx, "DAST " + e.DisplayName, when, $"dast.scan(common, {envRef})", tickets: true);
        if (ctx.RateLimit && c.RateLimit.Environments.Contains(e.Key))
            VerifyStage(w, ctx, "Rate-limit check " + e.DisplayName, when, $"dast.rateLimitCheck(common, {envRef})", tickets: false);
    }

    /// <summary>A post-deploy check on its own agent; reports are archived and optionally ticketed.</summary>
    private static void VerifyStage(CodeWriter w, GenerationContext ctx, string name, string when, string call, bool tickets)
    {
        w.Block($"stage({Quote(name)})", () =>
        {
            w.Block("when", () => { w.Line("beforeAgent true"); w.Line(when); });
            Agent(w, ctx, "jenkins/agents/deploy-pod.yaml");
            w.Block("options", () => w.Line("timeout(time: 60, unit: 'MINUTES')"));
            w.Block("steps", () => w.Block("script", () =>
            {
                Materialize(w, ctx);
                if (ctx.ExceptionsOnDeployAgents) w.Line("unstash 'pf-exceptions'");
                w.Line(call);
            }));
            w.Block("post", () =>
            {
                w.Block("always", () =>
                {
                    w.Line("archiveArtifacts artifacts: 'reports/**', allowEmptyArchive: true, fingerprint: true");
                    if (tickets && ctx.Ticketing) w.Block("script", () => w.Line("if (tickets) { tickets.file(common, 'dast') }"));
                });
                if (!ctx.IsKubernetes) w.Block("cleanup", () => w.Line("cleanWs()"));
            });
        });
    }

    public static bool HasDynamicTests(GenerationContext ctx) =>
        ctx.HasDast || ctx.Ephemeral || ctx.Authenticated || ctx.RateLimit || ctx.Scheduled;
}
